using System.Globalization;
using System.Text;

namespace XdlSharp.Generator;

// An integer typedef bound as a C# enum, with the macros that the config assigns to it as members.
internal sealed record TypedefEnum(string Name, string Header, string Underlying, bool IsFlags, List<EnumConstant> Members);

internal sealed record HeaderContent(List<EnumInfo> Enums, List<TypedefEnum> TypedefEnums, List<RecordInfo> Records, List<MacroInfo> Constants, List<FunctionInfo> Functions);

internal sealed class BindingWriter(AstModel model, TypeMapper mapper, GeneratorConfig config)
{
    // Every complete record written, nested ones included, for the layout checks.
    public List<RecordInfo> WrittenRecords { get; } = [];

    public string Write(HeaderContent content)
    {
        StringBuilder builder = new();
        builder.Append("// <auto-generated />\n// Generated by tools/XdlSharp.Generator from the XDL headers. Do not edit.\n\n");
        builder.Append("using System.Runtime.CompilerServices;\nusing System.Runtime.InteropServices;\n\nnamespace XdlSharp;\n");
        foreach (EnumInfo enumInfo in content.Enums)
        {
            WriteEnum(builder, enumInfo.CSharpName, UnderlyingOf(enumInfo.Constants), false, enumInfo.Constants);
        }

        foreach (TypedefEnum typedefEnum in content.TypedefEnums)
        {
            WriteEnum(builder, typedefEnum.Name, typedefEnum.Underlying, typedefEnum.IsFlags, typedefEnum.Members);
        }

        foreach (RecordInfo record in content.Records)
        {
            WriteRecord(builder, record);
        }

        if (content.Constants.Count == 0 && content.Functions.Count == 0)
        {
            return builder.ToString();
        }

        StringBuilder raw = new();
        builder.Append("\npublic static unsafe partial class Xdl\n{\n");
        bool first = true;
        foreach (MacroInfo constant in content.Constants)
        {
            WriteConstant(builder, constant);
            first = false;
        }

        foreach (FunctionInfo function in content.Functions)
        {
            if (!first)
            {
                builder.Append('\n');
            }

            WriteFunction(builder, raw, function);
            first = false;
        }

        if (raw.Length > 0)
        {
            builder.Append("\n    private static unsafe partial class Raw\n    {\n").Append(raw).Append("    }\n");
        }

        builder.Append("}\n");
        return builder.ToString();
    }

    public static string UnderlyingOf(IReadOnlyCollection<EnumConstant> constants)
    {
        if (constants.All(constant => constant.Value >= int.MinValue && constant.Value <= int.MaxValue))
        {
            return "int";
        }

        if (constants.All(constant => constant.Value >= 0 && constant.Value <= uint.MaxValue))
        {
            return "uint";
        }

        if (constants.All(constant => constant.Value >= long.MinValue && constant.Value <= long.MaxValue))
        {
            return "long";
        }

        return "ulong";
    }

    private static void WriteEnum(StringBuilder builder, string name, string underlying, bool isFlags, List<EnumConstant> members)
    {
        builder.Append('\n');
        if (isFlags)
        {
            builder.Append("[Flags]\n");
        }

        builder.Append("public enum ").Append(name);
        if (underlying != "int")
        {
            builder.Append(" : ").Append(underlying);
        }

        builder.Append("\n{\n");
        foreach (EnumConstant member in members)
        {
            if (!Fits(member.Value, underlying))
            {
                throw new InvalidOperationException($"{member.Name} = {member.Value} does not fit the {underlying} of {name}.");
            }

            string value = isFlags ? "0x" + member.Value.ToString("X", CultureInfo.InvariantCulture) : member.Value.ToString(CultureInfo.InvariantCulture);
            builder.Append("    ").Append(member.Name).Append(" = ").Append(value).Append(",\n");
        }

        builder.Append("}\n");
    }

    private void WriteRecord(StringBuilder builder, RecordInfo record)
    {
        builder.Append('\n');
        if (!record.IsComplete)
        {
            builder.Append("public struct ").Append(record.CSharpName).Append("\n{\n}\n");
            return;
        }

        WrittenRecords.Add(record);
        List<string> lines = [];
        List<RecordInfo> nested = [];
        List<(string Name, string Element, int Length)> inlineArrays = [];
        bool isUnsafe = false;
        foreach (FieldInfo field in record.Fields)
        {
            string name = CSharpNames.Escape(field.Name);
            if (field.Name == record.CSharpName)
            {
                throw new NotSupportedException($"The field {record.CSharpName}.{field.Name} has the name of its type.");
            }

            string prefix = record.IsUnion ? "[FieldOffset(0)] public " : "public ";
            if (field.AnonymousRecord != null)
            {
                field.AnonymousRecord.CSharpName = $"{record.CSharpName}_{field.Name}";
                nested.Add(field.AnonymousRecord);
                lines.Add($"{prefix}{field.AnonymousRecord.CSharpName} {name};");
                continue;
            }

            MType type = mapper.Resolve(field.Type!);
            if (type is MArray array)
            {
                string element = mapper.Render(array.Element, Usage.Field);
                if (TypeMapper.IsFixedBufferElement(array.Element))
                {
                    isUnsafe = true;
                    lines.Add($"{prefix}fixed {element} {name}[{array.Length}];");
                }
                else
                {
                    string arrayName = $"{record.CSharpName}_{field.Name}";
                    inlineArrays.Add((arrayName, element, array.Length));
                    lines.Add($"{prefix}{arrayName} {name};");
                }

                continue;
            }

            string rendered = mapper.Render(type, Usage.Field);
            isUnsafe |= rendered.StartsWith("delegate*", StringComparison.Ordinal);
            lines.Add($"{prefix}{rendered} {name};");
        }

        if (record.IsUnion)
        {
            builder.Append("[StructLayout(LayoutKind.Explicit)]\n");
        }

        builder.Append(isUnsafe ? "public unsafe struct " : "public struct ").Append(record.CSharpName).Append("\n{\n");
        foreach (string line in lines)
        {
            builder.Append("    ").Append(line).Append('\n');
        }

        builder.Append("}\n");
        foreach ((string name, string element, int length) in inlineArrays)
        {
            builder.Append("\n[InlineArray(").Append(length).Append(")]\npublic struct ").Append(name).Append("\n{\n    private ").Append(element).Append(" _element0;\n}\n");
        }

        foreach (RecordInfo nestedRecord in nested)
        {
            WriteRecord(builder, nestedRecord);
        }
    }

    private void WriteConstant(StringBuilder builder, MacroInfo macro)
    {
        MacroValue value = model.MacroValues[macro.Name];
        if (value.String != null)
        {
            builder.Append("    public static ReadOnlySpan<byte> ").Append(macro.Name).Append(" => ").Append(StringLiteral(value.String)).Append("u8;\n");
            return;
        }

        MType type = mapper.Resolve(value.Type, allowMacroOnly: true);
        if (value.Floating != null)
        {
            string suffix = type is MPrimitive { CSharp: "float" } ? "f" : "";
            builder.Append("    public const ").Append(mapper.Render(type, Usage.Public)).Append(' ').Append(macro.Name).Append(" = ")
                .Append(value.Floating).Append(suffix).Append(";\n");
            return;
        }

        Int128 integer = value.Integer!.Value;
        if (type is MEnum enumType)
        {
            string text = integer < 0 ? $"({integer})" : integer.ToString(CultureInfo.InvariantCulture);
            builder.Append("    public const ").Append(enumType.CSharpName).Append(' ').Append(macro.Name).Append(" = (").Append(enumType.CSharpName).Append(')')
                .Append(text).Append(";\n");
            return;
        }

        string csharp = mapper.Render(type, Usage.Public);
        if (!Fits(integer, csharp))
        {
            throw new InvalidOperationException($"The macro {macro.Name} = {integer} does not fit {csharp}.");
        }

        string literal = integer.ToString(CultureInfo.InvariantCulture) + csharp switch { "uint" => "u", "long" => "L", "ulong" => "UL", _ => "" };
        builder.Append("    public const ").Append(csharp).Append(' ').Append(macro.Name).Append(" = ").Append(literal).Append(";\n");
    }

    // clang prints the literal as written in C, quotes included; the escapes C and C# share pass through.
    private static string StringLiteral(string cLiteral)
    {
        if (!cLiteral.StartsWith('"') || !cLiteral.EndsWith('"'))
        {
            throw new NotSupportedException($"Unsupported string literal {cLiteral}.");
        }

        string body = cLiteral[1..^1];
        for (int index = 0; index < body.Length; index++)
        {
            if (body[index] == '\\')
            {
                index++;
                if (index >= body.Length || body[index] is not ('\\' or '"' or 'n' or 't' or 'r' or '0'))
                {
                    throw new NotSupportedException($"Unsupported escape in the string literal {cLiteral}.");
                }
            }
            else if (body[index] < 0x20 || body[index] > 0x7E)
            {
                throw new NotSupportedException($"Unsupported character in the string literal {cLiteral}.");
            }
        }

        return cLiteral;
    }

    private void WriteFunction(StringBuilder builder, StringBuilder raw, FunctionInfo function)
    {
        MType returnType = mapper.Resolve(function.Return);
        List<(string Name, MType Type)> parameters = function.Parameters
            .Select((parameter, index) => (CSharpNames.Escape(parameter.Name ?? $"arg{index}"), mapper.Resolve(parameter.Type))).ToList();
        string? returnedParameter = config.ReturnsParameter.TryGetValue(function.Name, out string? configured) ? CSharpNames.Escape(configured) : null;
        HashSet<string> retained = config.RetainedParameters.GetValueOrDefault(function.Name, []).Select(CSharpNames.Escape).ToHashSet();
        HashSet<string> spans = parameters.Where(parameter => TypeMapper.IsConstCharPointer(parameter.Type) && !retained.Contains(parameter.Name))
            .Select(parameter => parameter.Name).ToHashSet();

        string rawReturn = mapper.Render(returnType, Usage.Raw);
        List<string> rawParameters = parameters.Select(parameter => $"{mapper.Render(parameter.Type, Usage.Raw)} {parameter.Name}").ToList();
        string publicReturn = returnedParameter != null ? "ReadOnlySpan<byte>" : mapper.Render(returnType, Usage.Public);
        List<string> publicParameters = parameters.Select(parameter => PublicParameter(parameter.Name, parameter.Type, spans, returnedParameter)).ToList();
        string dllImport = $"[DllImport(\"{LibraryOf(config, function.Header)}\", CallingConvention = CallingConvention.Cdecl, ExactSpelling = true)]";

        if (rawReturn == publicReturn && rawParameters.SequenceEqual(publicParameters))
        {
            builder.Append("    ").Append(dllImport).Append("\n    public static extern ").Append(rawReturn).Append(' ').Append(function.Name)
                .Append('(').Append(string.Join(", ", rawParameters)).Append(");\n");
            return;
        }

        raw.Append("        ").Append(dllImport).Append("\n        public static extern ").Append(rawReturn).Append(' ').Append(function.Name)
            .Append('(').Append(string.Join(", ", rawParameters)).Append(");\n");

        List<string> arguments = parameters.Select(parameter => Argument(parameter.Name, parameter.Type, spans)).ToList();
        string call = $"Raw.{function.Name}({string.Join(", ", arguments)})";
        string indent = spans.Count > 0 ? "            " : "        ";

        builder.Append("    [MethodImpl(MethodImplOptions.AggressiveInlining)]\n    public static ").Append(publicReturn).Append(' ').Append(function.Name)
            .Append('(').Append(string.Join(", ", publicParameters)).Append(")\n    {\n");
        if (spans.Count > 0)
        {
            IEnumerable<string> pins = parameters.Where(parameter => spans.Contains(parameter.Name))
                .Select(parameter => $"{Local(parameter.Name)} = &MemoryMarshal.GetReference({parameter.Name})");
            builder.Append("        fixed (byte* ").Append(string.Join(", ", pins)).Append(")\n        {\n");
        }

        if (returnedParameter != null)
        {
            WriteReturnedParameterBody(builder, indent, function, returnType, call, returnedParameter);
        }
        else
        {
            builder.Append(indent).Append(ReturnStatement(returnType, publicReturn, call)).Append('\n');
        }

        if (spans.Count > 0)
        {
            builder.Append("        }\n");
        }

        builder.Append("    }\n");
    }

    // SDL may return the parameter itself. Handing back the caller's span keeps the memory tracked by the GC and lets the
    // compiler stop it from outliving a stackalloc; a pointer would dangle once the fixed block ends.
    private static void WriteReturnedParameterBody(StringBuilder builder, string indent, FunctionInfo function, MType returnType, string call, string parameter)
    {
        if (!TypeMapper.IsConstCharPointer(returnType))
        {
            throw new NotSupportedException($"{function.Name} must return const char * to return a parameter.");
        }

        string local = Local(parameter);
        builder.Append(indent).Append("byte* __result = ").Append(call).Append(";\n");
        builder.Append(indent).Append("if (__result == null)\n").Append(indent).Append("{\n").Append(indent).Append("    return default;\n").Append(indent).Append("}\n\n");
        builder.Append(indent).Append("if (__result == ").Append(local).Append(")\n").Append(indent).Append("{\n");
        builder.Append(indent).Append("    // C stops at the first terminator, so the returned span does too.\n");
        builder.Append(indent).Append("    int __end = ").Append(parameter).Append(".IndexOf((byte)0);\n");
        builder.Append(indent).Append("    return __end < 0 ? ").Append(parameter).Append(" : ").Append(parameter).Append("[..__end];\n");
        builder.Append(indent).Append("}\n\n");
        builder.Append(indent).Append("return MemoryMarshal.CreateReadOnlySpanFromNullTerminated(__result);\n");
    }

    private string PublicParameter(string name, MType type, IReadOnlySet<string> spans, string? returnedParameter)
    {
        if (spans.Contains(name))
        {
            string scoped = returnedParameter != null && returnedParameter != name ? "scoped " : "";
            return $"{scoped}ReadOnlySpan<byte> {name}";
        }

        return $"{mapper.Render(type, Usage.Public)} {name}";
    }

    private string Argument(string name, MType type, IReadOnlySet<string> spans)
    {
        if (spans.Contains(name))
        {
            return Local(name);
        }

        if (type is MPrimitive { CSharp: "bool" })
        {
            return $"{name} ? (byte)1 : (byte)0";
        }

        string publicType = mapper.Render(type, Usage.Public);
        string rawType = mapper.Render(type, Usage.Raw);
        if (publicType.StartsWith("Pointer<Pointer<", StringComparison.Ordinal))
        {
            return $"({rawType})({publicType[8..^1]}*){name}";
        }

        if (publicType.StartsWith("delegate*", StringComparison.Ordinal))
        {
            return $"({rawType}){name}";
        }

        return name;
    }

    private static string ReturnStatement(MType returnType, string publicReturn, string call)
    {
        if (publicReturn.StartsWith("delegate*", StringComparison.Ordinal))
        {
            return $"return ({publicReturn}){call};";
        }

        if (returnType is MPrimitive { CSharp: "void" })
        {
            return call + ";";
        }

        if (returnType is MPrimitive { CSharp: "bool" })
        {
            return $"return {call} != 0;";
        }

        if (publicReturn.StartsWith("Pointer<Pointer<", StringComparison.Ordinal))
        {
            return $"return ({publicReturn[8..^1]}*){call};";
        }

        return $"return {call};";
    }

    public static string? LibraryOf(GeneratorConfig config, string header)
    {
        int slash = header.IndexOf('/');
        return slash < 0 ? null : config.Libraries.GetValueOrDefault(header[..slash]);
    }

    private static string Local(string parameter)
    {
        return "__" + parameter.TrimStart('@');
    }

    private static bool Fits(Int128 value, string type)
    {
        return type switch
        {
            "byte" => value >= byte.MinValue && value <= byte.MaxValue,
            "sbyte" => value >= sbyte.MinValue && value <= sbyte.MaxValue,
            "short" => value >= short.MinValue && value <= short.MaxValue,
            "ushort" => value >= ushort.MinValue && value <= ushort.MaxValue,
            "int" => value >= int.MinValue && value <= int.MaxValue,
            "uint" => value >= uint.MinValue && value <= uint.MaxValue,
            "long" => value >= long.MinValue && value <= long.MaxValue,
            "ulong" => value >= ulong.MinValue && value <= ulong.MaxValue,
            "nint" => value >= int.MinValue && value <= int.MaxValue,
            "nuint" => value >= uint.MinValue && value <= uint.MaxValue,
            _ => false,
        };
    }
}
