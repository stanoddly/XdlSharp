using System.Text;

namespace XdlSharp.Generator;

// Writes the same table of sizes and offsets twice: in C, measured by the C compiler of the target, and in C#, measured by
// the .NET runtime. The checks compare the two on each platform, the browser included.
internal sealed class LayoutWriter(AstModel model, TypeMapper mapper)
{
    public (string C, string CSharp) Write(IReadOnlyList<string> headers, IReadOnlyList<RecordInfo> records, IReadOnlyList<(string CSharpName, string CSpelling)> enums)
    {
        StringBuilder c = new();
        c.Append("// Generated by tools/XdlSharp.Generator from the XDL headers. Do not edit.\n\n#include <stddef.h>\n");
        foreach (string header in headers)
        {
            c.Append("#include <").Append(header).Append(">\n");
        }

        c.Append("\ntypedef struct XdlSharpLayout\n{\n    const char *name;\n    size_t value;\n} XdlSharpLayout;\n\nstatic const XdlSharpLayout layouts[] = {\n");

        StringBuilder csharp = new();
        csharp.Append("// <auto-generated />\n// Generated by tools/XdlSharp.Generator from the XDL headers. Do not edit.\n\nnamespace XdlSharp.Checks;\n\n");
        csharp.Append("internal static unsafe partial class ManagedLayout\n{\n    public static List<(string Name, nuint Value)> Get()\n    {\n");
        csharp.Append("        List<(string Name, nuint Value)> entries = [];\n");

        foreach (RecordInfo record in records)
        {
            (string root, string? path) = CAccess(record);
            string size = path == null ? $"sizeof({root})" : $"sizeof((({root} *)0)->{path})";
            c.Append("    { \"").Append(record.CSharpName).Append("\", ").Append(size).Append(" },\n");
            csharp.Append("        {\n            ").Append(record.CSharpName).Append(" value = default;\n            byte* start = (byte*)&value;\n");
            csharp.Append("            entries.Add((\"").Append(record.CSharpName).Append("\", (nuint)sizeof(").Append(record.CSharpName).Append(")));\n");
            foreach (FieldInfo field in record.Fields)
            {
                string memberPath = path == null ? field.Name : $"{path}.{field.Name}";
                string offset = path == null ? $"offsetof({root}, {memberPath})" : $"offsetof({root}, {memberPath}) - offsetof({root}, {path})";
                c.Append("    { \"").Append(record.CSharpName).Append('.').Append(field.Name).Append("\", ").Append(offset).Append(" },\n");

                string name = CSharpNames.Escape(field.Name);
                bool isFixedBuffer = field.Type != null && mapper.Resolve(field.Type) is MArray array && IsFixedBuffer(array);
                string address = isFixedBuffer ? $"(byte*)value.{name}" : $"(byte*)&value.{name}";
                csharp.Append("            entries.Add((\"").Append(record.CSharpName).Append('.').Append(field.Name).Append("\", (nuint)(")
                    .Append(address).Append(" - start)));\n");
            }

            csharp.Append("        }\n");
        }

        foreach ((string csharpName, string cSpelling) in enums)
        {
            c.Append("    { \"").Append(csharpName).Append("\", sizeof(").Append(cSpelling).Append(") },\n");
            csharp.Append("        entries.Add((\"").Append(csharpName).Append("\", (nuint)sizeof(").Append(csharpName).Append(")));\n");
        }

        c.Append("};\n\n#if defined(_WIN32)\n__declspec(dllexport)\n#else\n__attribute__((visibility(\"default\")))\n#endif\n");
        c.Append("const XdlSharpLayout *xdlsharp_layouts(int *count)\n{\n    *count = (int)(sizeof(layouts) / sizeof(layouts[0]));\n    return layouts;\n}\n");
        csharp.Append("        return entries;\n    }\n}\n");
        return (c.ToString(), csharp.ToString());
    }

    private bool IsFixedBuffer(MArray array)
    {
        return array.Element is MPrimitive;
    }

    // A nested anonymous record has no C name: it is measured as a member of the outermost named record.
    private (string Root, string? Path) CAccess(RecordInfo record)
    {
        if (record.Parent == null)
        {
            return (record.CSpelling ?? CSpellingOf(record), null);
        }

        (string root, string? path) = CAccess(record.Parent);
        return (root, path == null ? record.ParentField : $"{path}.{record.ParentField}");
    }

    private string CSpellingOf(RecordInfo record)
    {
        if (model.TypedefsByName.TryGetValue(record.Tag!, out TypedefInfo? typedef) && typedef.Underlying is CNamedType { IsTag: true } named && named.Name == record.Tag)
        {
            return record.Tag!;
        }

        return (record.IsUnion ? "union " : "struct ") + record.Tag;
    }
}
